/**
 * Fixed tray layouts, in board-cell units. Each level has several arrangements (narrow and tall for phones, square,
 * wide and short for wide screens); `chooseArrangement` (src/ui/fit.ts) picks the one that gives the biggest cells
 * for the viewport. Each item is anchored top-left in its own square box (max(width, height) cells), and the cells it
 * can ever occupy are the union of its rotations. Layouts are packed (exhaustive search) so those unions never
 * overlap, so rotating an item in the tray cannot change the tray size or touch a neighbour. Boxes themselves may
 * overlap where one item's unused corner holds another.
 */
export interface TraySlot {
  /** 1-based grid column / row of the box's top-left cell. */
  col: number
  row: number
}

export interface TrayLayout {
  cols: number
  rows: number
  slots: Record<string, TraySlot>
}

