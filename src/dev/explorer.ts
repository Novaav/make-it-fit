import data from './explorer.fixture.json'
import { uniqueRotations, type Level, type Orientation, type Placement } from '../engine'

type Row = [string, number, number, number]
interface RawExample {
  label: string
  perfect: boolean
  items: string[]
  chaos: number
  weight: number
  count: number
  rotated: number
  placements: Row[]
}
const raw = data as unknown as Record<string, { legal: number; winning: number; perfect: number; examples: RawExample[] }>

/** One solver-verified complete placement (mandatory items included), ready to fill into the suitcase. */
export interface ExplorerExample {
  id: string
  label: string
  perfect: boolean
  items: string[]
  chaos: number
  weight: number
  /** Selectable items in the pack. */
  count: number
  /** Items (mandatory included) placed in a turned orientation. */
  rotated: number
  placements: Placement[]
}

/** Item-subset counts from the verifier (item combinations, not physical layouts). */
export function explorerSummary(levelId: string) {
  const s = raw[levelId]
  return s ? { legal: s.legal, winning: s.winning, perfect: s.perfect } : null
}

/**
 * The developer Solution Explorer's examples for a level: every perfect pack plus a few representative normal wins.
 * Generated by `verify_levels.py` (never searched in the browser); `explorer.test.ts` replays each one through the engine.
 */
export function explorerExamples(level: Level): ExplorerExample[] {
  return (raw[level.id]?.examples ?? []).map((e, index) => ({
    id: `${level.id}-${index}`,
    label: e.label,
    perfect: e.perfect,
    items: e.items,
    chaos: e.chaos,
    weight: e.weight,
    count: e.count,
    rotated: e.rotated,
    placements: e.placements.map(([itemId, rotation, x, y]) => {
      const item = level.items.find((i) => i.id === itemId)
      if (!item) throw new Error(`Explorer item ${itemId} missing from level ${level.id}`)
      const orientation: Orientation = uniqueRotations(item.cells)[rotation].orientation
      return { itemId, orientation, x, y }
    }),
  }))
}
